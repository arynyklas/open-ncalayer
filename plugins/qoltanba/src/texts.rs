//! Qoltanba's message bundles, Russian and Kazakh: the texts of its replies (and of its own
//! windows, which OpenNCALayer's dialogs replace), by key.

/// The language of the replies: the request's `lang`, `kk` for Kazakh, anything else Russian.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Lang {
    Ru,
    Kk,
}

impl Lang {
    /// The language a `lang` value selects.
    pub(crate) fn of(lang: &str) -> Lang {
        if lang == "kk" { Lang::Kk } else { Lang::Ru }
    }
}

