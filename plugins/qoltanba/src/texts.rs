/// The text of `key` in `lang`; `None` for a key the bundles lack (Java's
/// `MissingResourceException`).
pub(crate) fn get(lang: Lang, key: &str) -> Option<&'static str> {
    BUNDLE
        .iter()
        .find(|(k, ..)| *k == key)
        .map(|(_, ru, kk)| match lang {
            Lang::Ru => *ru,
            Lang::Kk => *kk,
        })
}

/// The text of `key` in `lang`, for keys of the bundles.
///
/// # Panics
///
/// If the bundles lack `key` (a port error).
pub(crate) fn text(lang: Lang, key: &str) -> &'static str {
    get(lang, key).unwrap_or_else(|| panic!("no message {key}"))
}
