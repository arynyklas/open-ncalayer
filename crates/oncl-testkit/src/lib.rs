//! Test helpers shared by OpenNCALayer crates.
//!
//! Paths are resolved against the workspace root, so tests work regardless of
//! the current directory `cargo test` runs them from.

use serde::Deserialize;
use std::path::{Path, PathBuf};

#[cfg(windows)]
pub mod dll;
pub mod plugin;

/// Root of the Cargo workspace (the directory holding the top-level `Cargo.toml`).
pub fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("oncl-testkit lives at <root>/crates/oncl-testkit")
        .to_path_buf()
}

/// Path of a downloaded NCANode fixture: `target/fixtures/ncanode/<name>`.
///
/// # Panics
///
/// Panics if the file is missing; the fixtures are fetched by
/// `cargo xtask fetch-fixtures`.
pub fn ncanode(name: &str) -> PathBuf {
    let path = workspace_root().join("target/fixtures/ncanode").join(name);
    assert!(
        path.is_file(),
        "NCANode fixture {} is missing: run `cargo xtask fetch-fixtures`",
        path.display()
    );
    path
}

/// Path of a fixture committed to the repository: `fixtures/<rel>`.
pub fn fixture(rel: &str) -> PathBuf {
    workspace_root().join("fixtures").join(rel)
}

/// Reads a whole file, panicking with the path on failure.
pub fn read(path: impl AsRef<Path>) -> Vec<u8> {
    let path = path.as_ref();
    std::fs::read(path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()))
}

/// The existing local path `local` spelled as a network path that reaches it: on Windows
/// through the drive's administrative share (`\\localhost\C$\…`), elsewhere as a `//`-path
/// (a network path by OpenNCALayer's rule, which POSIX systems resolve locally). `None`,
/// with a note on stderr, when it is not reachable (no administrative share): the caller
/// skips.
pub fn network_form(local: &Path) -> Option<String> {
    let local = std::path::absolute(local).expect("an absolute path");
    let network = if cfg!(windows) {
        let text = local.to_str().expect("a UTF-8 path");
        let (drive, rest) = text.split_at(2);
        format!(r"\\localhost\{}${rest}", &drive[..1])
    } else {
        format!("/{}", local.display())
    };
    if std::fs::metadata(&network).is_err() {
        eprintln!("skipped: {network} is not reachable");
        return None;
    }
    Some(network)
}

/// A PKCS#12 container of the synthetic NCA-like PKI in `fixtures/synthetic/`, generated by
/// `cargo xtask gen-fixtures` and described by `fixtures/synthetic/fixtures.toml`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SyntheticKey {
    /// File name without `.p12`, e.g. `user-gost2015-sign`.
    pub name: String,
    /// Path of the `.p12` file.
    pub path: PathBuf,
    /// Container password.
    pub password: String,
    /// Aliases of all entries, in the order `pkcs12::load` returns them.
    pub aliases: Vec<String>,
    /// Path of the `.cer` of the self-signed root the entries chain to.
    pub root: PathBuf,
    /// Path of the `.cer` of the CA that issued the entries: the root itself, an intermediate
    /// CA, or — for a self-signed root's own key — that root.
    pub issuer: PathBuf,
}

/// `fixtures.toml` as written by `cargo xtask gen-fixtures`.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SyntheticManifest {
    p12: Vec<SyntheticEntry>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SyntheticEntry {
    name: String,
    password: String,
    root: String,
    issuer: String,
    aliases: Vec<String>,
}

/// All synthetic containers, in `fixtures.toml` order.
///
/// # Panics
///
/// If `fixtures/synthetic/fixtures.toml` is missing or malformed.
pub fn synthetic_all() -> Vec<SyntheticKey> {
    let path = fixture("synthetic/fixtures.toml");
    let text = String::from_utf8(read(&path))
        .unwrap_or_else(|e| panic!("{} is not UTF-8: {e}", path.display()));
    let manifest: SyntheticManifest =
        toml::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    manifest
        .p12
        .into_iter()
        .map(|e| SyntheticKey {
            path: fixture(&format!("synthetic/{}.p12", e.name)),
            root: fixture(&format!("synthetic/{}", e.root)),
            issuer: fixture(&format!("synthetic/{}", e.issuer)),
            name: e.name,
            password: e.password,
            aliases: e.aliases,
        })
        .collect()
}

/// The synthetic container `fixtures/synthetic/<name>.p12`.
///
/// # Panics
///
/// If `fixtures.toml` does not list `name`.
pub fn synthetic(name: &str) -> SyntheticKey {
    synthetic_all()
        .into_iter()
        .find(|k| k.name == name)
        .unwrap_or_else(|| {
            panic!("no synthetic fixture {name:?} in fixtures/synthetic/fixtures.toml")
        })
}

/// DER of the synthetic certificate `fixtures/synthetic/<name>.cer`, e.g. `inter-gost2015`.
///
/// # Panics
///
/// If the file is missing.
pub fn synthetic_cert(name: &str) -> Vec<u8> {
    read(fixture(&format!("synthetic/{name}.cer")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn workspace_root_holds_workspace_manifest() {
        let manifest = String::from_utf8(read(workspace_root().join("Cargo.toml"))).unwrap();
        assert!(manifest.contains("[workspace]"));
    }

    #[test]
    fn fixture_is_under_fixtures_dir() {
        assert_eq!(
            fixture("a/b.der"),
            workspace_root().join("fixtures").join("a/b.der")
        );
    }

    #[test]
    fn synthetic_issuer_and_cert_resolve() {
        let leaf = synthetic("inter-user-gost2015-sign");
        assert_eq!(leaf.issuer, fixture("synthetic/inter-gost2015.cer"));
        assert_eq!(leaf.root, fixture("synthetic/root-gost2015.cer"));
        assert_eq!(read(&leaf.issuer), synthetic_cert("inter-gost2015"));
        let user = synthetic("user-gost2015-sign");
        assert_eq!(user.issuer, user.root);
    }

    #[test]
    #[should_panic(expected = "run `cargo xtask fetch-fixtures`")]
    fn missing_ncanode_fixture_tells_how_to_fetch() {
        ncanode("no-such-fixture.bin");
    }
}
