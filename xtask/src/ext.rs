//! `cargo xtask ext build`: the browser extension, for Chromium (MV3) and Firefox (MV2).
//!
//! `extension/src/host.js` is generated from [`HOST_NAME`] first, so the scripts and the
//! native messaging manifests name the same host. Each browser then gets, under the output
//! directory (`target/extension/` from the CLI):
//! - `<browser>/`: the unpacked extension, `manifest.json` rendered from
//!   `extension/manifests/<browser>.json` plus every file of `extension/src/`;
//! - `openncalayer-chromium-<version>.zip` / `openncalayer-firefox-<version>.xpi` (unsigned):
//!   the same files.

use std::fs::{self, File};
use std::io::Write;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail, ensure};
use base64::Engine;
use base64::engine::general_purpose::STANDARD;
use oncl_ipc::ids::{
    CHROMIUM_EXTENSION_ID, CHROMIUM_EXTENSION_KEY, FIREFOX_EXTENSION_ID, HOST_NAME,
    chromium_extension_id,
};
use zip::write::SimpleFileOptions;
use zip::{CompressionMethod, DateTime, ZipWriter};

/// Extension version: the workspace version (xtask inherits it).
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Browsers and the extension of their archive.
const BROWSERS: [(&str, &str); 2] = [("chromium", "zip"), ("firefox", "xpi")];

/// One built extension.
#[derive(Debug)]
pub struct Package {
    /// `chromium` or `firefox`.
    pub browser: &'static str,
    /// The unpacked extension.
    pub dir: PathBuf,
    /// The zip (Chromium) or unsigned xpi (Firefox).
    pub archive: PathBuf,
}

/// Builds both extensions from `<root>/extension/` into `out`.
///
/// # Errors
///
/// If [`CHROMIUM_EXTENSION_ID`] does not belong to [`CHROMIUM_EXTENSION_KEY`], the version is
/// not a browser extension version, a manifest template is not valid JSON once rendered or
/// keeps a placeholder, or a file cannot be read or written.
pub fn build(root: &Path, out: &Path) -> anyhow::Result<Vec<Package>> {
    check_chromium_id()?;
    check_version(VERSION)?;
    let extension = root.join("extension");
    let src = extension.join("src");
    refresh(&src.join("host.js"), &host_js())?;
    let scripts = read_files(&src)?;

    let mut packages = Vec::new();
    for (browser, archive_extension) in BROWSERS {
        let template = extension.join("manifests").join(format!("{browser}.json"));
        let template = fs::read_to_string(&template)
            .with_context(|| format!("reading {}", template.display()))?;
        let manifest = render(&template).with_context(|| format!("{browser} manifest"))?;

        let mut files = vec![("manifest.json".to_owned(), manifest.into_bytes())];
        files.extend(scripts.iter().cloned());

        let dir = out.join(browser);
        if dir.exists() {
            fs::remove_dir_all(&dir).with_context(|| format!("removing {}", dir.display()))?;
        }
        fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
        for (name, bytes) in &files {
            let path = dir.join(name);
            fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))?;
        }
        let archive = out.join(format!(
            "openncalayer-{browser}-{VERSION}.{archive_extension}"
        ));
        write_archive(&archive, &files)
            .with_context(|| format!("writing {}", archive.display()))?;
        packages.push(Package {
            browser,
            dir,
            archive,
        });
    }
    Ok(packages)
}

/// `extension/src/host.js`: the native messaging host name for the background.
pub fn host_js() -> String {
    format!(
        "// Generated by `cargo xtask ext build` from `oncl_ipc::ids::HOST_NAME`; do not edit.\n\
         'use strict';\n\
         \n\
         const HOST_NAME = \"{HOST_NAME}\";\n"
    )
}

/// The manifest template with `{{VERSION}}`, `{{KEY}}` and `{{FIREFOX_ID}}` filled in.
///
/// # Errors
///
/// If a placeholder is left or the result is not JSON.
pub fn render(template: &str) -> anyhow::Result<String> {
    let rendered = template
        .replace("{{VERSION}}", VERSION)
        .replace("{{KEY}}", CHROMIUM_EXTENSION_KEY)
        .replace("{{FIREFOX_ID}}", FIREFOX_EXTENSION_ID);
    if let Some(at) = rendered.find("{{") {
        let line = rendered[at..].lines().next().unwrap_or_default();
        bail!("unknown placeholder: {line}");
    }
    serde_json::from_str::<serde_json::Value>(&rendered).context("not valid JSON")?;
    Ok(rendered)
}

fn check_chromium_id() -> anyhow::Result<()> {
    let spki = STANDARD
        .decode(CHROMIUM_EXTENSION_KEY)
        .context("CHROMIUM_EXTENSION_KEY is not base64")?;
    let id = chromium_extension_id(&spki);
    ensure!(
        id == CHROMIUM_EXTENSION_ID,
        "CHROMIUM_EXTENSION_ID is {CHROMIUM_EXTENSION_ID}, but CHROMIUM_EXTENSION_KEY gives {id}"
    );
    Ok(())
}

/// Browsers take one to four dot-separated integers of at most 65535.
fn check_version(version: &str) -> anyhow::Result<()> {
    let parts: Vec<&str> = version.split('.').collect();
    let valid = (1..=4).contains(&parts.len())
        && parts.iter().all(|part| {
            !part.is_empty()
                && part.bytes().all(|b| b.is_ascii_digit())
                && (part.len() == 1 || !part.starts_with('0'))
                && part.parse::<u16>().is_ok()
        });
    ensure!(
        valid,
        "version {version} is not a browser extension version"
    );
    Ok(())
}

/// Writes `contents` to `path` unless it already holds exactly that.
fn refresh(path: &Path, contents: &str) -> anyhow::Result<()> {
    if fs::read(path).ok().as_deref() == Some(contents.as_bytes()) {
        return Ok(());
    }
    fs::write(path, contents).with_context(|| format!("writing {}", path.display()))
}

/// Every file directly in `dir` as (name, bytes), sorted by name.
fn read_files(dir: &Path) -> anyhow::Result<Vec<(String, Vec<u8>)>> {
    let mut files = Vec::new();
    for entry in fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let entry = entry?;
        if !entry.file_type()?.is_file() {
            continue;
        }
        let name = entry
            .file_name()
            .into_string()
            .map_err(|name| anyhow::anyhow!("non-UTF-8 file name {}", name.display()))?;
        files.push((name, fs::read(entry.path())?));
    }
    files.sort();
    Ok(files)
}

/// A deflated zip of `files` with fixed timestamps, so equal inputs give equal archives.
fn write_archive(path: &Path, files: &[(String, Vec<u8>)]) -> anyhow::Result<()> {
    let options = SimpleFileOptions::default()
        .compression_method(CompressionMethod::Deflated)
        .last_modified_time(DateTime::default())
        .unix_permissions(0o644);
    let mut zip = ZipWriter::new(File::create(path)?);
    for (name, bytes) in files {
        zip.start_file(name.as_str(), options)?;
        zip.write_all(bytes)?;
    }
    zip.finish()?.sync_all()?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_fills_placeholders_and_rejects_unknown_ones() {
        let rendered =
            render(r#"{"v": "{{VERSION}}", "k": "{{KEY}}", "id": "{{FIREFOX_ID}}"}"#).unwrap();
        let value: serde_json::Value = serde_json::from_str(&rendered).unwrap();
        assert_eq!(value["v"], VERSION);
        assert_eq!(value["k"], CHROMIUM_EXTENSION_KEY);
        assert_eq!(value["id"], FIREFOX_EXTENSION_ID);

        let error = render(r#"{"v": "{{VERSOIN}}"}"#).unwrap_err();
        assert!(error.to_string().contains("{{VERSOIN}}"), "{error}");
        assert!(render(r#"{"v": "{{VERSION}}""#).is_err());
    }

    #[test]
    fn chromium_id_matches_the_key() {
        check_chromium_id().unwrap();
    }

    #[test]
    fn browser_versions() {
        for good in ["0.1.0", "1", "1.2.3.4", "65535.0"] {
            check_version(good).unwrap();
        }
        for bad in [
            "",
            "1.2.3.4.5",
            "0.1.0-beta.1",
            "01.2",
            "65536",
            "1..2",
            "+1",
        ] {
            assert!(check_version(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn host_js_names_the_host() {
        assert!(host_js().contains(&format!("const HOST_NAME = \"{HOST_NAME}\";")));
    }
}
