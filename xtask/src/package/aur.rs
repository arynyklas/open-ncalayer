//! The AUR package `openncalayer-bin` (roadmap D12): `PKGBUILD`, `.SRCINFO` and the install
//! script of a released version, from the release archive
//! `openncalayer-<version>-x86_64-unknown-linux-gnu.tar.gz` (built in the glibc 2.28
//! container, see [`super::linux`]) at its immutable release URL, checked by sha256.
//!
//! The package installs the programs into `/usr/lib/openncalayer/` with
//! `package-manager` (`pacman`) next to them: the daemon reads it and leaves its updates to
//! pacman, however it is started (`openncalayer::lifecycle::PACKAGE_MANAGER_FILE`). Each
//! user's desktop is integrated at the daemon's first start, as for the other packages;
//! pacman, as root, touches no home directory.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail};
use oncl_update::Version;

use crate::index::release_asset_url;

/// The package's name.
pub const PKGNAME: &str = "openncalayer-bin";
/// The install script's file name.
pub const INSTALL: &str = "openncalayer-bin.install";
const PKGDESC: &str =
    "Open replacement for NCALayer: signing with NCA RK (Kazakhstan) keys for websites";
const URL: &str = "https://github.com/arynyklas/open-ncalayer";
/// What the programs need from the system (their `DT_NEEDED` in the glibc 2.28 build:
/// glibc, libgcc, fontconfig) and what the windows load at run time (libxkbcommon and its
/// X11 part).
const DEPENDS: [&str; 5] = [
    "glibc",
    "gcc-libs",
    "fontconfig",
    "libxkbcommon",
    "libxkbcommon-x11",
];
const OPTDEPENDS: [&str; 4] = [
    "xdg-desktop-portal: the file dialogs of the windows",
    "zenity: the file dialogs without a desktop portal",
    "pcsclite: hardware tokens and ID cards (experimental)",
    "ccid: USB smart card readers",
];

/// pacman's `pkgver` of `version`: hyphens are not allowed, and a pre-release must sort
/// before its release (`0.2.0-beta.1` → `0.2.0beta.1`, which `vercmp` puts below `0.2.0`).
pub fn pkgver(version: &Version) -> String {
    let text = version.to_string();
    let text = text.split('+').next().unwrap_or(&text);
    text.replace('-', "")
}

/// The release archive of `version`.
pub fn tarball_name(version: &Version) -> String {
    format!("openncalayer-{version}-x86_64-unknown-linux-gnu.tar.gz")
}

/// The package of `version`, with `pkgrel`, from the archive whose sha256 is `sha256`.
#[derive(Clone, Debug)]
pub struct Package {
    pub version: Version,
    pub pkgrel: u32,
    pub sha256: String,
}

impl Package {
    /// The package; `sha256` must be 64 lowercase hex digits.
    ///
    /// # Errors
    ///
    /// It is not, or `pkgrel` is 0.
    pub fn new(version: Version, pkgrel: u32, sha256: &str) -> anyhow::Result<Package> {
        let valid = sha256.len() == 64
            && sha256
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
        if !valid {
            bail!("{sha256:?} is not a lowercase hex sha256");
        }
        if pkgrel == 0 {
            bail!("pkgrel starts at 1");
        }
        Ok(Package {
            version,
            pkgrel,
            sha256: sha256.to_owned(),
        })
    }

    /// `<file>::<url>`: the archive under its own name, from the release.
    fn source(&self) -> String {
        let name = tarball_name(&self.version);
        format!("{name}::{}", release_asset_url(&self.version, &name))
    }

    /// The `PKGBUILD`.
    pub fn pkgbuild(&self) -> String {
        let quoted = |items: &[&str]| {
            items
                .iter()
                .map(|i| format!("'{i}'"))
                .collect::<Vec<_>>()
                .join(" ")
        };
        let dir = tarball_name(&self.version)
            .trim_end_matches(".tar.gz")
            .to_owned();
        format!(
            r#"# Generated by `cargo xtask package aur` of OpenNCALayer; edit the generator, not this file.
# Maintainer: OpenNCALayer contributors <{URL}>
pkgname={PKGNAME}
pkgver={pkgver}
pkgrel={pkgrel}
pkgdesc='{PKGDESC}'
arch=('x86_64')
url='{URL}'
license=('Apache-2.0')
depends=({depends})
optdepends=({optdepends})
provides=('openncalayer')
conflicts=('openncalayer')
# The release's programs as they are: not stripped again, no debug package.
options=('!strip' '!debug')
install={INSTALL}
source=('{source}')
sha256sums=('{sha256}')

package() {{
  cd '{dir}'
  install -Dm755 openncalayer "$pkgdir/usr/lib/openncalayer/openncalayer"
  install -Dm755 nmhost "$pkgdir/usr/lib/openncalayer/nmhost"
  # The daemon leaves its updates to pacman when this file is next to it.
  printf 'pacman\n' > package-manager
  install -Dm644 package-manager "$pkgdir/usr/lib/openncalayer/package-manager"
  install -d "$pkgdir/usr/bin"
  ln -s /usr/lib/openncalayer/openncalayer "$pkgdir/usr/bin/openncalayer"
  printf '%s\n' '[Desktop Entry]' 'Type=Application' 'Name=OpenNCALayer' \
    'Comment=NCALayer-compatible signing service' 'Exec=/usr/bin/openncalayer run' \
    'Terminal=false' 'Categories=Utility;' > openncalayer.desktop
  install -Dm644 openncalayer.desktop "$pkgdir/usr/share/applications/openncalayer.desktop"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 NOTICE "$pkgdir/usr/share/licenses/$pkgname/NOTICE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
  install -Dm644 README.en.md "$pkgdir/usr/share/doc/$pkgname/README.en.md"
}}
"#,
            pkgver = pkgver(&self.version),
            pkgrel = self.pkgrel,
            depends = quoted(&DEPENDS),
            optdepends = quoted(&OPTDEPENDS),
            source = self.source(),
            sha256 = self.sha256,
        )
    }

    /// The `.SRCINFO`, as `makepkg --printsrcinfo` prints it for [`Package::pkgbuild`].
    pub fn srcinfo(&self) -> String {
        let mut out = String::new();
        // Writing to a `String` cannot fail.
        let _ = writeln!(out, "pkgbase = {PKGNAME}");
        let mut field = |key: &str, value: &str| {
            let _ = writeln!(out, "\t{key} = {value}");
        };
        field("pkgdesc", PKGDESC);
        field("pkgver", &pkgver(&self.version));
        field("pkgrel", &self.pkgrel.to_string());
        field("url", URL);
        field("install", INSTALL);
        field("arch", "x86_64");
        field("license", "Apache-2.0");
        for depend in DEPENDS {
            field("depends", depend);
        }
        for optdepend in OPTDEPENDS {
            field("optdepends", optdepend);
        }
        field("provides", "openncalayer");
        field("conflicts", "openncalayer");
        field("options", "!strip");
        field("options", "!debug");
        field("source", &self.source());
        field("sha256sums", &self.sha256);
        let _ = writeln!(out, "\npkgname = {PKGNAME}");
        out
    }

    /// Writes `PKGBUILD`, `.SRCINFO` and [`INSTALL`] into `dir`; returns them.
    ///
    /// # Errors
    ///
    /// A file cannot be written.
    pub fn write(&self, dir: &Path) -> anyhow::Result<Vec<PathBuf>> {
        fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        let files = [
            ("PKGBUILD", self.pkgbuild()),
            (".SRCINFO", self.srcinfo()),
            (INSTALL, INSTALL_SCRIPT.to_owned()),
        ];
        let mut written = Vec::new();
        for (name, text) in files {
            let path = dir.join(name);
            fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
            written.push(path);
        }
        Ok(written)
    }
}

/// The install script: what pacman, as root, cannot do for each user.
pub const INSTALL_SCRIPT: &str = r#"post_install() {
  echo 'OpenNCALayer: start it once as each user (openncalayer, or from the menu): it then'
  echo 'registers itself in the browsers and starts at login. Certificates are not installed.'
}

post_upgrade() {
  echo 'OpenNCALayer: the running daemon keeps the old version until it is restarted'
  echo '(the tray menu, or the next login).'
}

pre_remove() {
  echo 'OpenNCALayer: before removing, run "openncalayer integration uninstall" as each user'
  echo 'to remove its browser registration and autostart; the data directory stays.'
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    const SHA: &str = "a460f00e5ff4ceb0691cb2baa023c4da9013b7f5978b53053326dc88dc8e079d";

    fn package(version: &str) -> Package {
        Package::new(Version::parse(version).unwrap(), 1, SHA).unwrap()
    }

    #[test]
    fn pre_releases_sort_before_their_release() {
        assert_eq!(pkgver(&Version::parse("0.2.0").unwrap()), "0.2.0");
        assert_eq!(
            pkgver(&Version::parse("0.1.0-alpha.2").unwrap()),
            "0.1.0alpha.2"
        );
        assert_eq!(
            pkgver(&Version::parse("1.0.0-rc.1+build.5").unwrap()),
            "1.0.0rc.1"
        );
        assert!(Package::new(Version::parse("0.2.0").unwrap(), 1, "ABC").is_err());
        assert!(Package::new(Version::parse("0.2.0").unwrap(), 0, SHA).is_err());
        assert!(Package::new(Version::parse("0.2.0").unwrap(), 1, &SHA.to_uppercase()).is_err());
    }

    #[test]
    fn the_pkgbuild_downloads_the_immutable_release_archive() {
        let p = package("0.2.0-beta.1");
        let pkgbuild = p.pkgbuild();
        let url = "https://github.com/arynyklas/open-ncalayer/releases/download/v0.2.0-beta.1/\
                   openncalayer-0.2.0-beta.1-x86_64-unknown-linux-gnu.tar.gz";
        assert!(pkgbuild.contains(&format!(
            "source=('openncalayer-0.2.0-beta.1-x86_64-unknown-linux-gnu.tar.gz::{url}')"
        )));
        assert!(pkgbuild.contains(&format!("sha256sums=('{SHA}')")));
        assert!(pkgbuild.contains("pkgver=0.2.0beta.1\n"));
        assert!(pkgbuild.contains("cd 'openncalayer-0.2.0-beta.1-x86_64-unknown-linux-gnu'"));
        // Updates are pacman's: the marker next to the daemon.
        assert!(pkgbuild.contains("\"$pkgdir/usr/lib/openncalayer/package-manager\""));
        assert!(pkgbuild.contains("printf 'pacman\\n' > package-manager"));
        // No variable but makepkg's own in the URL: nothing it could fetch instead.
        assert!(!pkgbuild.contains("${"));
    }

    #[test]
    fn the_srcinfo_says_what_the_pkgbuild_says() {
        let p = package("0.2.0");
        let srcinfo = p.srcinfo();
        let pkgbuild = p.pkgbuild();
        for line in srcinfo.lines().filter_map(|l| l.strip_prefix('\t')) {
            let (key, value) = line.split_once(" = ").unwrap();
            let shown = match key {
                "pkgver" | "pkgrel" | "install" => format!("{key}={value}"),
                "pkgdesc" | "url" => format!("{key}='{value}'"),
                _ => format!("'{value}'"),
            };
            assert!(
                pkgbuild.contains(&shown),
                "{key}: {shown} is not in the PKGBUILD"
            );
        }
        assert!(srcinfo.starts_with("pkgbase = openncalayer-bin\n"));
        assert!(srcinfo.ends_with("\npkgname = openncalayer-bin\n"));
        // Hardware tokens are optional: the daemon opens pcsc-lite at run time.
        for optdepend in [
            "pcsclite: hardware tokens and ID cards (experimental)",
            "ccid: USB smart card readers",
        ] {
            assert!(
                srcinfo.contains(&format!("\toptdepends = {optdepend}\n")),
                "{optdepend}"
            );
            assert!(pkgbuild.contains(&format!("'{optdepend}'")), "{optdepend}");
        }

        let dir = tempfile::tempdir().unwrap();
        let written = p.write(dir.path()).unwrap();
        assert_eq!(written.len(), 3);
        assert_eq!(
            fs::read_to_string(dir.path().join(".SRCINFO")).unwrap(),
            srcinfo
        );
        assert!(INSTALL_SCRIPT.contains("integration uninstall"));
    }
}
